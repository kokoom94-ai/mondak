def _norm(t):
    t = (t or "").lower()
    for pat, rep in HOMONYM:
        t = re.sub(pat, rep, t)
    for pat in NEG_CANCEL:
        t = re.sub(pat, " [해소] ", t)
    return t

# ══════════ 1단계 — 관련성 ══════════
def gate_relevance(title, body="", channel=""):
    full = f"{title} {body}"
    t = full.lower()
    if not geo_hit(full):
        return False, "제주 지역 신호 없음"
    if sum(1 for r in OTHER_REGIONS if r in title) >= 2:
        return False, "전국 나열형"
    if any(w in t for w in PROMO):
        return False, "홍보·영업 글"
    if channel in ("blog", "cafe", "threads"):
        if not any(w in t for w in TOURIST_ACT):
            return False, "관광객 경험 아님"
        return True, "관광객 경험"
    if any(w in t for w in TOURIST_NEWS):
        return True, "관광 사안"
    if any(w in t for w in TOURIST_ACT):
        return True, "관광 맥락"
    if any(w in t for w in INCIDENT):
        if any(w in t for w in TOUR_PLACE):
            return True, "관광 시설 사건"
        if any(w in t for w in DAILY_PLACE):
            return False, "일상 공간 사건"
        return False, "관광 연결 없는 사건"
    return False, "관광 맥락 없음"

# ══════════ 2단계 — 유형 ══════════
MEDIA_MENTION = [r"방송에\s?나온", r"방송\s?출연\s?맛집", r"tv에\s?나온", r"티비에\s?나온",
                 r"유튜브에\s?나온", r"백종원", r"맛집으로\s?소개", r"소개된\s?맛집"]
PERSONNEL = ["임용","임명","취임","승진","인사","전보","내정","위촉","선임","해임","사임 처리",
             "감사패","표창","수상자","위원 위촉","이사장 공모","사장 공모"]

def gate_type(title, body="", channel=""):
    t = f"{title} {body}".lower()
    ttl = title.lower()
    if any(w in ttl for w in PERSONNEL): return "인사"
    if any(re.search(p, t) for p in MEDIA_MENTION):
        pass
    elif any(w in t for w in ENTERTAIN): return "연예"
    if any(w in t for w in AD):        return "광고"
    if any(w in t for w in INCIDENT):  return "사건"
    if any(w in t for w in GOV_ACT) and any(w in t for w in ["조례","정책","행정","예산","도의회","당국"]):
        return "행정"
    if channel in ("news",):           return "뉴스"
    return "후기"

# ══════════ 3단계 — 감성 ══════════
def _score(t, table):
    total, hits = 0, []
    for rx, wt, label in table:
        if re.search(rx, t):
            total += wt; hits.append(label)
    return total, hits

def gate_sentiment(title, body="", typ=""):
    t = _norm(f"{title} {body}")
    neg, reasons = _score(t, NEG_RX)
    pos, _       = _score(t, POS_RX)
    if typ == "사건":
        tt = _norm(title)
        for w, wt in INCIDENT_WEIGHT.items():
            if w in tt: neg += wt; reasons.append(w)
    if neg >= 3 and neg > pos:  return "부정", neg, pos, list(dict.fromkeys(reasons))[:6]
    if neg >= 1 and neg > pos:  return "부정약", neg, pos, list(dict.fromkeys(reasons))[:6]
    if pos >= 3 and pos > neg:  return "긍정", neg, pos, []
    return "중립", neg, pos, []

# ══════════ 분야 — 우선권 방식 ══════════
def categorize(title, body="", negative=False):
    """
    불만 글(negative=True)은 FIELD 순서(응대→비용→환경→교통…)를 그대로 따른다.
    그래야 "불친절한 흑돼지집" 이 먹거리가 아니라 응대·서비스로 잡힌다.
    중립·긍정 글은 무엇에 관한 글인지가 중요하므로 제목 등장 위치를 우선한다.
    """
    ttl = (title or "").lower(); bdy = (body or "").lower()
    if negative:
        for name, ws in FIELD:
            if any(w in ttl for w in ws): return name
        for name, ws in FIELD:
            if any(w in bdy for w in ws): return name
        return None
    best, pos = None, 10**9
    for name, ws in FIELD:
        for w in ws:
            k = ttl.find(w)
            if k >= 0 and k < pos: best, pos = name, k
    if best: return best
    for name, ws in FIELD:
        if any(w in bdy for w in ws): return name
    return None

def nature(title, body=""):
    t = f"{title} {body}".lower()
    for name, ws in NATURE:
        if any(w in t for w in ws): return name
    return "불만·후기"

# ══════════ 트랙 ══════════
VOICE_CH = ("blog", "cafe", "threads", "youtube")

def track_of(typ, nat, channel):
    """
    voice — 수요자가 직접 겪고 남긴 불만·후기. 정책 도출의 근거.
    risk  — 사건·이슈. 하나의 사건이 관광에 타격을 줄 수 있는지 감시.
    info  — 행정·홍보 소식. 지수에서 제외한다.
    """
    if typ == "사건" or nat == "사건사고":     return "risk"
    # 수요자 목소리는 '겪은 사람이 직접 쓴 글'만 인정한다.
    # 뉴스는 아무리 성격이 후기여도 voice가 아니다(홍보·소개 기사가 대부분).
    if channel in VOICE_CH:                    return "voice"
    return "info"

# ══════════ 통합 ══════════
def judge(item):
    title = item.get("title") or ""
    body  = item.get("description") or ""
    ch    = item.get("channel") or ""
    rel, rel_why = gate_relevance(title, body, ch)
    if rel is False:
        return {"keep": False, "stage": "관련성", "why": rel_why}
    typ = gate_type(title, body, ch)
    if typ in ("광고", "연예", "인사"):
        return {"keep": False, "stage": "유형", "why": typ}
    sent, neg, pos, why = gate_sentiment(title, body, typ)
    is_neg = sent.startswith("부정")
    cat = categorize(title, body, negative=is_neg)
    if cat is None and sent == "중립":
        return {"keep": False, "stage": "카테고리", "why": "분류 불가·중립"}
    nat = nature(title, body)
    trk = track_of(typ, nat, ch)
    return {"keep": True, "pending": rel is None, "type": typ, "category": cat, "nature": nat,
            "track": trk, "policy": FIELD_POLICY.get(cat or ""),
            "sentiment": "부정" if is_neg else sent,
            "strength": "강" if sent == "부정" else ("약" if sent == "부정약" else ""),
            "neg": neg, "pos": pos, "reasons": why,
            "rel_why": rel_why, "geo": geo_reason(f"{title} {body}")}
